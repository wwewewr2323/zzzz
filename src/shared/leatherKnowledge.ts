export function computeThicknessCompensationMm(
  materialId: string,
  edgeProcess: EdgeProcessType
): {
  liningWidthDeductionMm: number;
  liningHeightDeductionMm: number;
  boardInsetMm: number;
  bendRadiusAllowanceMm: number;
  skiveRequired: boolean;
  skiveTargetMm: number;
} {
  const mat = getMaterialById(materialId);
  const t = mat.thicknessMm;
  const skiveRequired = edgeProcess === 'folded' && t > mat.skivingRecommendedAboveMm;
  return {
    liningWidthDeductionMm: Math.round((2.0 + t * 1.4) * 10) / 10,
    liningHeightDeductionMm: Math.round((3.0 + t * 1.6) * 10) / 10,
    boardInsetMm: Math.round((3.5 + t * 1.5) * 10) / 10,
    bendRadiusAllowanceMm: Math.round(t * 0.65 * 10) / 10,
    skiveRequired,
    skiveTargetMm: edgeProcess === 'folded' ? 0.65 : 0.9,
  };
}

